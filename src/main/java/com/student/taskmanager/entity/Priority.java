package com.student.taskmanager.entity;

/**
 * Priority represents the urgency or importance of a student task.
 * 
 * - LOW: Routine tasks, can be delayed if needed.
 * - MEDIUM: Regular homework and weekly assignments.
 * - HIGH: Exams, project submissions, imminent deadlines.
 */
public enum Priority {
    LOW,
    MEDIUM,
    HIGH
}
